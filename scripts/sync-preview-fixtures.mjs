#!/usr/bin/env node
/**
 * Sync .planning/round*\/specs\/*.json into assets/preview-fixtures/
 * and regenerate the index.ts that Metro bundles.
 *
 * Run after generating a fresh round of specs:
 *   node scripts/sync-preview-fixtures.mjs
 *
 * Source of truth: .planning/round*\/specs\/ (where the validate harness
 * already writes generated specs).
 * Output: assets/preview-fixtures/{*.json,index.ts} (what the UI app
 * imports for offline `?fixture=<slug>` mode).
 *
 * Idempotent. If a slug exists in multiple rounds (e.g. round-6's
 * `hair-salon` and round-7's `hair-salon-v2`), both are kept — the
 * filename in `.planning` is the slug verbatim. If two rounds emit
 * the same slug, the latest round wins (lexical max of round number).
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, '..');
const PLANNING_DIR = path.join(REPO_ROOT, '.planning');
const FIXTURES_DIR = path.join(REPO_ROOT, 'assets', 'preview-fixtures');

/** "hair-salon-v2" → "hairSalonV2" — safe identifier for ES imports. */
function toCamel(slug) {
  return slug
    .split(/[-_]/)
    .map((part, i) => (i === 0 ? part : part[0].toUpperCase() + part.slice(1)))
    .join('');
}

// ── Collect specs from every round ────────────────────────────────────
// Latest round wins on duplicate slugs. Round name like "round7" sorts
// after "round6" lexically, so reverse-sort and pick the first hit.
const roundDirs = fs
  .readdirSync(PLANNING_DIR)
  .filter((d) => /^round\d+$/.test(d) && fs.existsSync(path.join(PLANNING_DIR, d, 'specs')))
  .sort()
  .reverse();

if (roundDirs.length === 0) {
  console.error('No .planning/round*\/specs\/ directories found.');
  process.exit(1);
}

const specsBySlug = new Map(); // slug -> { srcPath, round }
for (const round of roundDirs) {
  const specsDir = path.join(PLANNING_DIR, round, 'specs');
  for (const file of fs.readdirSync(specsDir)) {
    if (!file.endsWith('.json')) continue;
    const slug = file.replace(/\.json$/, '');
    if (specsBySlug.has(slug)) continue; // already taken by a later round
    specsBySlug.set(slug, { srcPath: path.join(specsDir, file), round });
  }
}

// ── Wipe + copy ──────────────────────────────────────────────────────
fs.mkdirSync(FIXTURES_DIR, { recursive: true });
for (const file of fs.readdirSync(FIXTURES_DIR)) {
  if (file.endsWith('.json')) fs.unlinkSync(path.join(FIXTURES_DIR, file));
}

const sortedSlugs = [...specsBySlug.keys()].sort();
for (const slug of sortedSlugs) {
  const { srcPath } = specsBySlug.get(slug);
  fs.copyFileSync(srcPath, path.join(FIXTURES_DIR, `${slug}.json`));
}

// ── Regenerate index.ts ──────────────────────────────────────────────
const importLines = sortedSlugs.map((slug) => `import ${toCamel(slug)} from './${slug}.json';`).join('\n');
const mapLines = sortedSlugs
  .map((slug) => {
    const ident = toCamel(slug);
    // `bakery: bakery` is shorthand-able; longer slugs need quoted keys.
    return slug === ident ? `  ${slug},` : `  '${slug}': ${ident},`;
  })
  .join('\n');

const indexSource = `/**
 * Bundled spec fixtures for offline UI development.
 *
 * Each entry is a complete InsForge spec (the same shape \`/get-spec\`
 * returns) for one business vertical. Lets a UI developer preview the
 * app without running the InsForge backend — load with
 * \`http://localhost:8081/?fixture=<slug>\`.
 *
 * AUTO-GENERATED by scripts/sync-preview-fixtures.mjs. Do not hand-edit;
 * re-run the script after dropping new specs into .planning/round{N}/specs/.
 */

${importLines}

export const PREVIEW_FIXTURES: Record<string, any> = {
${mapLines}
};

export const FIXTURE_SLUGS = Object.keys(PREVIEW_FIXTURES).sort();

/** Get a fixture spec by slug. Returns the raw \`/get-spec\`-shaped JSON. */
export function getPreviewFixture(slug: string): any | null {
  return PREVIEW_FIXTURES[slug] ?? null;
}
`;

fs.writeFileSync(path.join(FIXTURES_DIR, 'index.ts'), indexSource);

// ── Report ───────────────────────────────────────────────────────────
console.log(`✓ Synced ${sortedSlugs.length} fixtures from ${roundDirs.length} round(s)`);
console.log(`  Rounds scanned: ${roundDirs.join(', ')}`);
console.log(`  Output:         assets/preview-fixtures/`);
console.log('');
console.log('Slugs:');
for (const slug of sortedSlugs) {
  const { round } = specsBySlug.get(slug);
  console.log(`  ${slug.padEnd(22)} (from ${round})`);
}
